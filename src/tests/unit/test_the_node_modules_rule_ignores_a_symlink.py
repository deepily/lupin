"""
THE DEFECT THIS CLOSES: `.gitignore` carried `node_modules/` — a TRAILING SLASH, which
matches DIRECTORIES ONLY. Every fleet worktree receives its `node_modules` as a SYMLINK
(`src/scripts/link-worktree-artifacts.sh` borrows it from the main checkout), and a
symlink is not a directory, so the rule missed it and every worktree carried a permanent
`?? node_modules` in `git status`. The rule was correct on the day it was written and was
overtaken by the borrow script — the fence did not move when the thing it fenced changed
shape.

WHY THE ASSERTION IS BEHAVIOURAL AND NOT TEXTUAL. Asserting "the line has no trailing
slash" pins today's SPELLING, not the PROPERTY, and would go green for a rule that is
spelled differently and still broken. These cases plant the REAL rule line — read out of
the REAL `.gitignore` — into a throwaway repo and ask GIT what it does with a symlink.
Change the bare `node_modules` rule in `.gitignore` back to `node_modules/` and
`test_a_symlinked_node_modules_is_ignored` reddens by name.

THE TWO SIDES HAVE DIFFERENT PROVENANCE, deliberately. The rule under test is derived
from the production file; the expectation ("a symlink named node_modules must be
invisible") is hand-written here. A comparison whose two sides come from one source
cannot disagree — see CLAUDE.md § A COMPARISON WHOSE TWO SIDES COME FROM ONE SOURCE.

⚠️ ONE ARM CANNOT CARRY THIS ALONE. A real DIRECTORY named `node_modules` is ignored
under BOTH spellings, so `test_a_real_node_modules_directory_is_still_ignored` is a
no-regression check and is NOT the guard — on its own it would report green against the
very defect this file exists for.
"""

import subprocess

from pathlib import Path

import pytest

import cosa.utils.util as cu


PROJECT_ROOT = cu.get_project_root()
GITIGNORE    = Path( PROJECT_ROOT ) / ".gitignore"


def _node_modules_rules():
    """
    Requires:
        - the repo's .gitignore is readable

    Ensures:
        - returns every non-comment rule line whose whole value names node_modules,
          stripped — the population, so a caller can assert on its SIZE before using it
        - a vacuous empty list is the caller's to catch, never silently treated as "fine"
    """
    lines = GITIGNORE.read_text().splitlines()
    return [ line.strip() for line in lines
             if line.strip().rstrip( "/" ) == "node_modules" and not line.strip().startswith( "#" ) ]


def _probe_repo( tmp_path, rule ):
    """
    Requires:
        - tmp_path is an empty directory
        - rule is the .gitignore line to plant

    Ensures:
        - returns a fresh git repo containing ONLY that ignore rule
        - the repo is real: git decides, this helper does not reimplement matching
    """
    tmp_path.mkdir( parents=True, exist_ok=True )
    subprocess.run( [ "git", "init", "-q" ], cwd=tmp_path, check=True )
    ( tmp_path / ".gitignore" ).write_text( rule + "\n" )
    return tmp_path


def _visible( repo ):
    """Ensures: the set of `git status --porcelain` entries, one per line, stripped."""
    out = subprocess.run(
        [ "git", "status", "--porcelain" ], cwd=repo, capture_output=True, text=True, check=True
    )
    return { line.strip() for line in out.stdout.splitlines() if line.strip() }


def test_the_node_modules_rule_is_found_at_all():
    """
    POSITIVE CONTROL — without it every case below passes vacuously on an empty
    extraction. A loop over nothing is green; so is a parametrize over nothing.
    """
    rules = _node_modules_rules()
    assert len( rules ) == 1, (
        f"expected exactly ONE node_modules rule in {GITIGNORE}, found {len( rules )}: {rules}. "
        "Zero means the extraction is looking in the wrong place and every other case here "
        "is vacuous; more than one means the rule this guard pins is ambiguous."
    )


def test_a_symlinked_node_modules_is_ignored( tmp_path ):
    """
    🔴 THIS IS THE GUARD. Restore the trailing slash on the node_modules rule and this case —
    and only this case — goes red.

    Ensures:
        - a SYMLINK named node_modules at the repo root is invisible to `git status`
        - git itself answers; the rule is the production one, not a copy
    """
    rule   = _node_modules_rules()[ 0 ]
    target = tmp_path / "elsewhere"
    target.mkdir()
    repo   = _probe_repo( tmp_path / "repo", rule )
    ( repo / "node_modules" ).symlink_to( target )

    assert ( repo / "node_modules" ).is_symlink(), "the probe must plant a SYMLINK — that is the whole variable"

    visible = _visible( repo )
    assert not any( "node_modules" in entry for entry in visible ), (
        f"rule {rule!r} leaves a SYMLINKED node_modules visible: {sorted( visible )}. "
        "A trailing slash matches directories only, and every worktree's node_modules is a symlink."
    )


def test_a_real_node_modules_directory_is_still_ignored( tmp_path ):
    """
    NO-REGRESSION, NOT THE GUARD. Both spellings ignore a real directory, so this case
    cannot discriminate — it is here to prove the fix did not give up the original
    purpose, and it must never be read as evidence the symlink case is covered.
    """
    rule = _node_modules_rules()[ 0 ]
    repo = _probe_repo( tmp_path / "repo", rule )
    ( repo / "node_modules" ).mkdir()
    ( repo / "node_modules" / "left-pad.js" ).write_text( "module.exports = 0\n" )

    visible = _visible( repo )
    assert not any( "node_modules" in entry for entry in visible ), (
        f"rule {rule!r} leaves a real node_modules DIRECTORY visible: {sorted( visible )}"
    )


def test_the_probe_repo_does_not_ignore_everything( tmp_path ):
    """
    DISCRIMINATION CONTROL. Without it, a probe repo that ignored every path would satisfy
    both cases above and this file would report green while measuring nothing.
    """
    rule = _node_modules_rules()[ 0 ]
    repo = _probe_repo( tmp_path / "repo", rule )
    ( repo / "an-ordinary-file.txt" ).write_text( "visible\n" )

    visible = _visible( repo )
    assert any( "an-ordinary-file.txt" in entry for entry in visible ), (
        "the probe repo reports an ordinary untracked file as ignored — the repo, not the "
        f"rule, is swallowing everything; status was {sorted( visible )}"
    )
