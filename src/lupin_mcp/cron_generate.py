"""
Write every Lupin background cron line from job-registry.json.

A job opts in with "cron_managed": true; "cron_enabled": false keeps its lines out of the block while its tag still clears the old ones. Each of its schedule entries becomes one line that runs
src/scripts/cron-job.sh <job> <cron|boot>, which loads one environment and runs the job through job_run.
The command and its settings are read from the registry at run time, so changing a flag needs no reinstall.

Usage:  python -m lupin_mcp.cron_generate [--only JOB] [--print | --diff | --install | --uninstall | --status]
--only JOB writes just that job's lines, with no header. Every other crontab line stays as it was. The test VM uses it for vector-refresh.
A Claude seat never installs. A person runs --install from the main checkout.
"""
import argparse
import contextlib
import datetime
import difflib
import os
import pathlib
import shlex
import sys

import cosa.rest.job_registry as jr
from lupin_mcp import host_snapshot as hs
from cosa.repo.symindex import librarian_tick as lt
from cosa.rest.job_service import expand, paths_of

ENTRY_SCRIPT = "src/scripts/cron-job.sh"
BLOCK_TAG    = lt.GENERATED_BLOCK_TAG                                 # ends the header comment, so a re-run removes the old header too
LOCK_OWNER   = "cron-generate"
BACKUP_DIR   = "io/jobs/crontab-backups"
HEADER       = f"# Generated by lupin_mcp.cron_generate from src/conf/job-registry.json; edit the registry, not these lines {BLOCK_TAG}"


def managed_jobs( registry ):
    """
    Pick the jobs whose lines this tool writes.

    Requires:
        - registry is the dict load_registry returns
    Ensures:
        - returns the jobs with cron_managed true, in registry order
        - raises ValueError for a managed job with no cron_tag, because its old lines could not be found again
        - raises ValueError for a job that has a run block, a cron_tag or a cron or after-boot schedule entry and is neither managed nor given a cron_exclusion_reason, so no job is left out without a stated reason
    """
    for job in registry[ "jobs" ]:
        scheduled = any( "cron" in entry or "after_boot_seconds" in entry for entry in job.get( "schedule", [] ) )
        if ( job.get( "run" ) or job.get( "cron_tag" ) or scheduled ) and not job.get( "cron_managed" ) and not ( job.get( "cron_exclusion_reason" ) or "" ).strip():
            raise ValueError( f"job {job[ 'job' ]} runs, has a cron_tag or is scheduled but is neither cron_managed nor given a cron_exclusion_reason" )
    jobs = [ job for job in registry[ "jobs" ] if job.get( "cron_managed" ) ]
    for job in jobs:
        if not job.get( "cron_tag" ): raise ValueError( f"job {job[ 'job' ]} is cron_managed but has no cron_tag" )
    return jobs


def lines_for_job( job, root, data, environ ):
    """
    Build the cron lines of one job.

    Requires:
        - job is a managed registry job; root is the main checkout
    Ensures:
        - returns [] for a job with cron_enabled false: its tag stays in the block's tags, so an install still removes the job's old lines
        - returns one line per schedule entry that has a cron or after_boot_seconds value; every_seconds entries have no cron form and add none
        - a cron entry is "<schedule> <command> # <tag>"; a boot entry is "@reboot sleep <n> && <command> # <tag>", or "@reboot <command> # <tag>" for n 0
        - the command is the entry script with the job name and cron or boot, appending to the job's cron_log (default io/jobs/<job>/cron.log)
    """
    if job.get( "cron_enabled", True ) is False: return []
    values = paths_of( root, data )
    log    = expand( job.get( "cron_log", "{root}/io/jobs/" + job[ "job" ] + "/cron.log" ), *values )
    script = shlex.quote( f"{root}/{ENTRY_SCRIPT}" )
    out    = []
    for entry in job[ "schedule" ]:
        if "cron" in entry:
            out.append( f"{entry[ 'cron' ]} {script} {job[ 'job' ]} cron >> {shlex.quote( log )} 2>&1 # {job[ 'cron_tag' ]}" )
        elif "after_boot_seconds" in entry:
            wait = f"sleep {entry[ 'after_boot_seconds' ]} && " if entry[ "after_boot_seconds" ] else ""
            out.append( f"@reboot {wait}{script} {job[ 'job' ]} boot >> {shlex.quote( log )} 2>&1 # {job[ 'cron_tag' ]}" )
    return out


def generate( root, environ, only=None ):
    """
    Build the whole block, and the names its install replaces.

    Requires:
        - root holds src/conf/job-registry.json
        - only is None, or the name of a cron_managed job
    Ensures:
        - returns ( lines, tags, legacy ): lines start with the header comment; tags is the tuple of every "# <tag>" the block owns, header tag included; legacy is the tuple of substrings the jobs' cron_replaces name
        - with only, lines hold just that job's lines (no header) and tags and legacy name just that job, so a merge touches no other line
    Raises:
        - ValueError when only names no cron_managed job
    """
    registry = jr.load_registry( root )
    from cosa.repo.symindex.paths import data_dir
    data     = data_dir( root )
    jobs     = managed_jobs( registry )
    if only is not None:
        jobs = [ job for job in jobs if job[ "job" ] == only ]
        if not jobs: raise ValueError( f"--only names {only}, which is not a cron_managed job" )
    lines    = [] if only is not None else [ HEADER ]
    for job in jobs: lines.extend( lines_for_job( job, root, data, environ ) )
    tags     = ( *( () if only is not None else ( BLOCK_TAG, ) ), *( f"# {job[ 'cron_tag' ]}" for job in jobs ) )
    legacy   = tuple( word for job in jobs for word in job.get( "cron_replaces", [] ) )
    return lines, tags, legacy


def make_log_folders( lines ):
    """
    Make the folder of each log a line appends to.

    Requires:
        - lines are generated lines, each holding ">> <log> 2>&1" with the log shell-quoted
    Ensures:
        - the shell opens a log before the job starts, so a missing folder would stop the run
        - every log's parent folder exists afterwards; lines with no log (the header) are skipped
    """
    for line in lines:
        if " >> " not in line: continue
        log = shlex.split( line.split( " >> ", 1 )[ 1 ] )[ 0 ]
        pathlib.Path( log ).parent.mkdir( parents=True, exist_ok=True )


def main( argv=None, environ=None, now=None, out=print, err=None, crontab_cmd=None ):
    """
    Print, diff, install, remove or report the generated block.

    Requires:
        - argv holds at most one of --print, --diff, --install, --uninstall, --status; the default is --print
    Ensures:
        - --backup-dir prints the backup folder, relative to the root, and does nothing else
        - --print writes the block and changes nothing; --diff writes the unified diff the install would make and changes nothing
        - a run that would change nothing writes no backup, no log folder and no crontab, and says so; two runs in one second cannot overwrite the first backup
        - --install and --uninstall go through the librarian's locked crontab editor: a timestamped backup under io/jobs/crontab-backups first, no backup no write, old tagged and legacy lines replaced, never added to
        - --install prints the backup folder and the diff it applied
        - --status says how many lines of the block are installed
        - returns 0, or 1 with the reason on err when the install is refused or fails
    """
    environ = os.environ if environ is None else environ
    err     = err or ( lambda text: print( text, file=sys.stderr ) )
    now     = now or datetime.datetime.now().astimezone()
    cmd     = crontab_cmd or lt.crontab_command( environ, "CRON_GENERATE_CRONTAB" )
    parser  = argparse.ArgumentParser( description="Write the Lupin cron lines from the job registry." )
    parser.add_argument( "--root", default=None )
    parser.add_argument( "--only", default=None, help="write only this job's lines (a cron_managed job name)" )
    parser.add_argument( "--backup-dir", action="store_true", help="print the crontab backup folder, relative to the root, and exit" )
    mode    = parser.add_mutually_exclusive_group()
    for name in ( "print", "diff", "install", "uninstall", "status" ): mode.add_argument( f"--{name}", action="store_true" )
    args    = parser.parse_args( argv )
    if args.backup_dir:
        out( BACKUP_DIR )
        return 0
    root    = args.root or environ.get( "LUPIN_ROOT" ) or str( pathlib.Path.cwd() )
    with contextlib.redirect_stdout( sys.stderr ):                    # the configuration manager prints a banner on import; keep stdout clean for --print
        try: lines, tags, legacy = generate( root, environ, args.only )
        except ValueError as error:
            err( f"cron-generate: {error}" )
            return 1
    old     = hs.crontab_text( cmd=cmd ) or ""
    new     = lt.merge_lines( old, [] if args.uninstall else lines, tags, legacy )
    delta   = "".join( difflib.unified_diff( old.splitlines( keepends=True ), new.splitlines( keepends=True ), "crontab.before", "crontab.after" ) )
    if args.status and args.only is not None:
        out( lt.status_text( old, tags[ 0 ], len( lines ) ) )
        return 0
    if args.status:
        out( lt.status_text( old, BLOCK_TAG, 1 ) + f"; {sum( 1 for line in old.splitlines() if line.rstrip().endswith( tuple( tags[ 1: ] ) ) )} of {len( lines ) - 1} job lines" )
        return 0
    if args.diff:
        out( delta or "no change" )
        return 0
    if not ( args.install or args.uninstall ):
        out( "\n".join( lines ) )
        return 0
    if new == old:
        out( "no change: the crontab already holds this block, so no backup was written and nothing was rewritten" )
        return 0
    backups = f"{root}/{BACKUP_DIR}"
    if args.install: make_log_folders( lines )
    try: lt.edit_crontab( [] if args.uninstall else lines, environ, cmd, backups, now, tag=tags, owner=LOCK_OWNER, legacy=legacy )
    except ( lt.InstallRefused, RuntimeError ) as error:
        err( f"cron-generate: {error}" )
        return 1
    out( f"backup of the old crontab: {backups}/crontab-{now.strftime( '%Y%m%d-%H%M%S' )}.txt" )
    out( delta or "no change" )
    return 0


if __name__ == "__main__":  # pragma: no cover - process entry point
    sys.exit( main() )
