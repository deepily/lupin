"""
State models for the Bug Fix Expediter pipeline.

Defines the phase enum, data models for each pipeline stage,
and the complete BFEState TypedDict.
"""

from enum import Enum
from typing import Optional, TypedDict

from pydantic import BaseModel, Field


class BFEPhase( Enum ):
    """Phase machine for the Bug Fix Expediter pipeline."""
    # Active phases
    PACKAGING            = "packaging"
    DIAGNOSING           = "diagnosing"
    PROPOSING            = "proposing"
    FIXING               = "fixing"
    COMMITTING           = "committing"
    RESUBMITTING         = "resubmitting"
    RETRYING             = "retrying"

    # Waiting phases
    WAITING_CONFIRMATION = "waiting_confirmation"

    # Terminal phases
    COMPLETED            = "completed"
    FAILED               = "failed"
    SKIPPED              = "skipped"


class DeadJobContext( BaseModel ):
    """
    Forensic context extracted from a dead (failed/interrupted) job.

    Requires:
        - id_hash, job_type, user_id, user_email, session_id, status, question_text are non-empty
        - status is "failed" or "interrupted"

    Ensures:
        - All fields populated from job_history table
        - stack_trace extracted from metadata_json if available
    """
    id_hash          : str
    job_type         : str
    user_id          : str
    user_email       : str
    session_id       : str
    status           : str                    # "failed" or "interrupted"
    question_text    : str
    error            : Optional[ str ]        = None
    stack_trace      : Optional[ str ]        = None
    routing_command  : Optional[ str ]        = None
    duration_seconds : Optional[ float ]      = None
    metadata_json    : Optional[ dict ]       = Field( default_factory=dict )
    created_at       : Optional[ str ]        = None
    started_at       : Optional[ str ]        = None
    completed_at     : Optional[ str ]        = None


class DiagnosisResult( BaseModel ):
    """
    Root cause analysis output from the diagnosis phase.

    Requires:
        - root_cause is non-empty
        - confidence is between 0.0 and 1.0

    Ensures:
        - Structured diagnosis for downstream proposal generation
    """
    root_cause          : str
    error_category      : str          # config, code_bug, dependency, timeout, resource, unknown
    confidence          : float = Field( ge=0.0, le=1.0 )
    evidence            : list[ str ]  = Field( default_factory=list )
    affected_components : list[ str ]  = Field( default_factory=list )
    is_transient        : bool         = False


class ProposedFix( BaseModel ):
    """
    A proposed fix generated by the propose phase.

    Requires:
        - title and description are non-empty
        - confidence is between 0.0 and 1.0

    Ensures:
        - Actionable fix proposal with risk assessment
    """
    title            : str
    description      : str
    fix_type         : str          # config_change, code_patch, retry, manual
    confidence       : float = Field( ge=0.0, le=1.0 )
    risk_level       : str          = "low"
    estimated_effort : str          = "minimal"
    changes          : list[ dict ] = Field( default_factory=list )


class FixResult( BaseModel ):
    """
    Outcome of applying a proposed fix.

    Ensures:
        - Clear success/failure signal for retry decision
        - Phase 5 git fields populated after run_git_strategy() completes
    """
    applied        : bool
    success        : bool
    details        : str            = ""
    retry_eligible : bool           = False
    # Verification-loop diagnostics (populated when tester verification runs)
    attempts       : int                 = 0
    last_stderr    : Optional[ str ]     = None   # tail of last tester_output when verification fails
    # Phase 5 additions (populated after run_git_strategy)
    git_strategy       : Optional[ str ] = None   # "commit_only" | "branch_and_pr" | "branch_only" | None
    commit_hash        : Optional[ str ] = None
    branch_name        : Optional[ str ] = None
    pr_url             : Optional[ str ] = None
    # Phase 6 additions (populated after resubmit_original_job)
    resubmitted_job_id : Optional[ str ] = None


class BFEState( TypedDict ):
    """Complete state for a Bug Fix Expediter run."""
    # Input
    dead_job_id      : str
    extra_context    : str

    # Packaging Phase
    dead_job_context : Optional[ DeadJobContext ]

    # Diagnosis Phase
    diagnosis        : Optional[ DiagnosisResult ]

    # Proposal Phase
    proposed_fixes   : list[ ProposedFix ]
    selected_fix     : Optional[ ProposedFix ]
    user_approved    : bool

    # Fix Phase
    fix_result       : Optional[ FixResult ]

    # Retry Phase
    retry_job_id     : Optional[ str ]
    retry_status     : Optional[ str ]

    # Meta
    phase            : str
    error            : Optional[ str ]


def create_initial_state( dead_job_id: str, extra_context: str = "" ) -> BFEState:
    """
    Create initial BFEState for a new Bug Fix Expediter run.

    Requires:
        - dead_job_id is non-empty

    Ensures:
        - Returns BFEState with phase=PACKAGING and all fields initialized

    Args:
        dead_job_id: The id_hash of the dead job to fix
        extra_context: Optional user-provided context

    Returns:
        BFEState: Initial pipeline state
    """
    return BFEState(
        dead_job_id      = dead_job_id,
        extra_context    = extra_context,
        dead_job_context = None,
        diagnosis        = None,
        proposed_fixes   = [],
        selected_fix     = None,
        user_approved    = False,
        fix_result       = None,
        retry_job_id     = None,
        retry_status     = None,
        phase            = BFEPhase.PACKAGING.value,
        error            = None,
    )


