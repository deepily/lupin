# Re-export shared exception types from TFE (defined in session 9056c113 Phase C).
# These are agent-agnostic — the checkpoint-resume pattern uses identical semantics
# across TFE and BFE, so we share the exception classes to keep the dispatch
# machinery (resume_job factory, STALLED state transitions) uniform.
#
# Lazy module-level __getattr__ (PEP 562) avoids a circular import: TFE's state
# imports BFE's DiagnosisResult/FixResult as a base, so a direct `from tfe.state
# import ...` here would create a cycle at module-init time. Deferring the
# import until first attribute access breaks the cycle.
def __getattr__( name ):
    if name in ( "VoiceGateTimeoutError", "VoiceGateUnreachableError", "StalledException", "CheckpointData" ):
        from cosa.agents.test_fix_expediter.state import (
            VoiceGateTimeoutError, VoiceGateUnreachableError, StalledException, CheckpointData,
        )
        return { "VoiceGateTimeoutError"     : VoiceGateTimeoutError,
                 "VoiceGateUnreachableError" : VoiceGateUnreachableError,
                 "StalledException"          : StalledException,
                 "CheckpointData"            : CheckpointData }[ name ]
    raise AttributeError( f"module {__name__} has no attribute {name}" )


def quick_smoke_test():
    """Quick smoke test for BFE state models."""
    import cosa.utils.util as cu

    cu.print_banner( "BFE State Models Smoke Test", prepend_nl=True )

    try:
        # 1: BFEPhase enum
        assert BFEPhase.PACKAGING.value == "packaging"
        assert BFEPhase.COMPLETED.value == "completed"
        assert BFEPhase.COMMITTING.value == "committing"
        assert len( BFEPhase ) == 11
        print( "✓ BFEPhase enum correct (11 values)" )

        # 2: DeadJobContext
        ctx = DeadJobContext(
            id_hash="dr-test::user1", job_type="deep_research",
            user_id="user1", user_email="t@t.com", session_id="s1",
            status="failed", question_text="test query", error="boom"
        )
        assert ctx.status == "failed"
        assert ctx.stack_trace is None
        print( "✓ DeadJobContext validates correctly" )

        # 3: DiagnosisResult
        diag = DiagnosisResult(
            root_cause="Missing config key", error_category="config", confidence=0.9
        )
        assert diag.is_transient == False
        print( "✓ DiagnosisResult validates correctly" )

        # 4: ProposedFix
        fix = ProposedFix(
            title="Add key", description="Add missing key to INI",
            fix_type="config_change", confidence=0.95
        )
        assert fix.risk_level == "low"
        print( "✓ ProposedFix validates correctly" )

        # 5: FixResult
        result = FixResult( applied=True, success=True, details="Key added" )
        assert result.retry_eligible == False
        assert result.git_strategy is None
        assert result.commit_hash is None
        assert result.branch_name is None
        assert result.pr_url is None
        # Phase 5 git fields accept values
        result_with_git = FixResult(
            applied=True, success=True, details="Key added",
            git_strategy="commit_only", commit_hash="abc1234"
        )
        assert result_with_git.git_strategy == "commit_only"
        assert result_with_git.commit_hash == "abc1234"
        print( "✓ FixResult validates correctly (+ Phase 5 git fields)" )

        # 6: create_initial_state
        state = create_initial_state( "dr-test::user1", "extra info" )
        assert state[ "dead_job_id" ] == "dr-test::user1"
        assert state[ "phase" ] == "packaging"
        assert state[ "diagnosis" ] is None
        print( "✓ create_initial_state works correctly" )

        print( "\n✓ BFE State Models smoke test completed successfully" )

    except Exception as e:
        print( f"\n✗ Smoke test failed: {e}" )
        import traceback
        traceback.print_exc()


if __name__ == "__main__":
    quick_smoke_test()
